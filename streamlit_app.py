import numpy as np
import pandas as pd
import streamlit as st

st.title("Data Science Project")
st.write(
    "Welcome! This app presents DS 201 Project."
)
st.write("Hello! I am learning streamlit.")

# Text Input
analyst_name = st.text_input("Analyst Name:", "Data Scientist")

# Slider (label, min_value, max_value, default_value)
confidence_level = st.slider("Select Confidence Threshold (%):", 50, 100, 95)

# Dropdown / Selectbox
target_region = st.selectbox(
    "Select Target Region:", ["North America", "Europe", "Asia-Pacific"]
)

radio_test = st.radio("Report Granularity", ["Daily", "Weekly", "Monthly"])

# Action Button
if st.button("Generate Summary"):
    st.success(
        f"Report generated by **{analyst_name}** for **{target_region}** at a **{confidence_level}%** confidence threshold on a **{radio_test}** basis."
    )


